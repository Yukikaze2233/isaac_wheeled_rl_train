def module_source_path(name):
    """Return the current source file for a known logical module name."""
    module = MODULES[name.removesuffix(".py")]
    return PACKAGE_ROOT.joinpath(*module.split(".")).with_suffix(".py")


def relative_module_source(name):
    """Return its repository path for source freezing and receipt validation."""
    return module_source_path(name).relative_to(REPOSITORY_ROOT).as_posix()


def package_source_files():
    """Bind package initializers and transitive Python sources in frozen runs."""
    files = sorted((REPOSITORY_ROOT / "src").rglob("*.py"))
    files.extend(REPOSITORY_ROOT / name for name in (
        "scripts/train_chassis.py", "scripts/evaluate_flat_policy.py",
        "scripts/export_chassis_candidate.py", "scripts/replay_v7_ordinary.py",
        "scripts/chassis_remote_job.py", "tools/v7ctl.py",
    ))
    return [path.relative_to(REPOSITORY_ROOT).as_posix() for path in files]
